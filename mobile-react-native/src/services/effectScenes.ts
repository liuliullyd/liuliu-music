/** Persisted legacy presets only; the new visible catalog never calls this path. */
export function presetTuning(name: string): {
  gains: number[];
  advanced: AdvancedEffects;
} {
  const presets: Record<string, number[]> = {
    开车旅途: [6, 10, 3, 0, -1, -1, 0, -1, 2, 6],
    超重低音: [-6.5, -5, -3, 1.5, 3, -1, -2.5, -0.5, 3.5, 5],
    车载音响: [12, 6, -3, 1, -2, 1, -3, 2, -3, 2],
    'DTS 风格': [4, 4, 2, 2, 0, 0, 2, 2, 4, 5],
    电影: [3, 3, 1, 1, -1, -1, 2, 2, 4, 3],
    舞曲: [5, 5, 4, 4, 1, 1, 2, 2, 4, 5],
    游戏空间: [4, 4, 2, 2, 1, 1, 4, 4, 5, 4],
    深沉低音: [8, 8, 6, 6, 3, 3, 0, 0, -2, -3],
  };
  return {
    gains: presets[name] ?? Array(10).fill(0),
    advanced:
      name === '超重低音'
        ? {
            ...flatAdvancedEffects(),
            clarity: 30,
            reverb: 20,
            dynamics: 40,
            mode: 'speakers',
          }
        : flatAdvancedEffects(),
  };
}
